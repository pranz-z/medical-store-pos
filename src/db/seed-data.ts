export interface SeedUnitData {
  name: string;
  factorToBase: number;
  /** Selling price in minor units per unit. */
  price: number;
  isDefaultSale?: boolean;
}

export interface SeedBatchData {
  expiryDate: string;
  /** Quantity received in base units. */
  qty: number;
  /** Cost in minor units per base unit. */
  costPerBaseUnit: number;
  /** Index into SEED_SUPPLIERS. */
  supplier?: number;
}

export interface SeedProductData {
  sku: string;
  name: string;
  genericName?: string;
  strength?: string;
  form?: string;
  manufacturer?: string;
  /** Key of SEED_CATEGORIES. */
  category: string;
  baseUnit: string;
  taxClass: "vat" | "exempt";
  requiresRx?: boolean;
  controlledSchedule?: string;
  coldChain?: boolean;
  sellableLoose?: boolean;
  storageNotes?: string;
  /** Reorder threshold in base units. */
  reorderLevel?: number;
  units: SeedUnitData[];
  batches: SeedBatchData[];
}

/** Unit helper: `u(name, factorToBase, price, isDefaultSale?)`. */
const u = (
  name: string,
  factorToBase: number,
  price: number,
  isDefaultSale = false,
): SeedUnitData => ({
  name,
  factorToBase,
  price,
  isDefaultSale,
});

/** Batch helper: `b(expiryDate, qty, costPerBaseUnit, supplierIndex?)`. */
const b = (
  expiryDate: string,
  qty: number,
  costPerBaseUnit: number,
  supplier?: number,
): SeedBatchData => ({
  expiryDate,
  qty,
  costPerBaseUnit,
  supplier,
});

